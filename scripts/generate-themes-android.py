#!/usr/bin/env python3
"""Ports iOS's generated theme palettes to Kotlin, value for value.

iOS generates `OpenCode/Core/Theme/ThemePalette+Generated.swift` with
`scripts/generate-themes.ts` (OKLab/OKLCH derivation from the web app's theme
JSON). Android does not re-derive anything: this script reads that generated
Swift file and writes the same numbers as Kotlin data, so both apps show the
exact same colours. Run it again whenever iOS regenerates its themes:

    python3 scripts/generate-themes-android.py [path/to/ThemePalette+Generated.swift]

Default input: ../opencode-ios/OpenCode/Core/Theme/ThemePalette+Generated.swift
Output: core/src/main/kotlin/ai/opencode/core/ui/ThemePaletteGenerated.kt
Python 3 standard library only.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT.parent / "opencode-ios/OpenCode/Core/Theme/ThemePalette+Generated.swift"
OUTPUT = ROOT / "core/src/main/kotlin/ai/opencode/core/ui/ThemePaletteGenerated.kt"

DEFINITION = re.compile(r"static let (\w+) = ThemeDefinition\(\s*id: \.(\w+),\s*title: \"([^\"]+)\",(.*?)\n  \)\n", re.S)
VARIANT = re.compile(r"(light|dark): ThemeVariant\((.*?)\n    \)", re.S)
FIELD = re.compile(
    r"(\w+): ThemeRGBA\(r: ([\d.]+), g: ([\d.]+), b: ([\d.]+)(?:, a: ([\d.]+))?\)\s*(/\*.*?\*/)?"
)

# Swift `AppTheme` case → Kotlin enum entry.
ENUM_NAMES = {
    "opencode": "OpenCode",
    "tokyonight": "TokyoNight",
    "catppuccin": "Catppuccin",
    "dracula": "Dracula",
    "rosepine": "RosePine",
    "github": "GitHub",
}


def number(text: str) -> str:
    return text if "." in text else text + ".0"


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    swift = source.read_text()
    out = [
        "// Generated by scripts/generate-themes-android.py from iOS's",
        "// OpenCode/Core/Theme/ThemePalette+Generated.swift (itself generated by",
        "// scripts/generate-themes.ts). Do not edit by hand; rerun the script.",
        "@file:Suppress(\"ktlint\")",
        "",
        "package ai.opencode.core.ui",
        "",
        "/** The curated themes' resolved light and dark palettes, ported value for value from iOS. */",
        "internal object GeneratedThemePalettes {",
    ]
    names = []
    for match in DEFINITION.finditer(swift):
        name, case, title, body = match.groups()
        names.append(name)
        out.append(f"    val {name} = ThemeDefinition(")
        out.append(f"        id = AppTheme.{ENUM_NAMES[case]},")
        out.append(f"        title = \"{title}\",")
        for variant in VARIANT.finditer(body):
            kind, fields = variant.groups()
            out.append(f"        {kind} = ThemeVariant(")
            for field in FIELD.finditer(fields):
                key, r, g, b, a, comment = field.groups()
                args = f"{number(r)}, {number(g)}, {number(b)}"
                if a:
                    args += f", {number(a)}"
                suffix = f" {comment}" if comment else ""
                out.append(f"            {key} = ThemeRGBA({args}),{suffix}")
            out.append("        ),")
        out.append("    )")
        out.append("")
    if not names:
        sys.exit(f"No ThemeDefinition found in {source}")
    out[-1:] = ["}", ""]
    OUTPUT.write_text("\n".join(out))
    print(f"Wrote {len(names)} themes to {OUTPUT.relative_to(ROOT)}: {', '.join(names)}")


if __name__ == "__main__":
    main()
