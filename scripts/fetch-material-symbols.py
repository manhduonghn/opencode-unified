#!/usr/bin/env python3
"""Fetches Material Symbols (Rounded) icons and converts them to Android vector drawables.

Reads `scripts/material-symbols.txt` and writes `core/src/main/res/drawable/ms_<name>.xml`
(and `ms_<name>_fill.xml` for filled icons). Python 3 standard library only.

    python3 scripts/fetch-material-symbols.py          # fetch missing icons
    python3 scripts/fetch-material-symbols.py --force  # refetch every icon
    python3 scripts/fetch-material-symbols.py --prune  # also delete ms_*.xml not in the list

List file format, one icon per line (`#` starts a comment):

    <material symbol name> [fill] [mirror]

- `fill`: the filled variant (iOS `.fill` symbols), written as `ms_<name>_fill.xml`.
- `mirror`: directional icon, mirrored in right-to-left layouts (`android:autoMirrored`).

Find names at https://fonts.google.com/icons?icon.style=Rounded. To add an icon for an SF
Symbol: add its line here, run the script, then add the `SFSymbol` entry in
`core/src/main/kotlin/ai/opencode/core/ui/SFSymbol.kt` and its row in docs/parity/core-ui.md.
"""

import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "scripts/material-symbols.txt"
OUT = ROOT / "core/src/main/res/drawable"
URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{style}/24px.svg"

PATH = re.compile(r'<path[^>]*\sd="([^"]+)"')
VIEWBOX = re.compile(r'viewBox="([-\d.]+) ([-\d.]+) ([\d.]+) ([\d.]+)"')


def parse_list() -> list[tuple[str, bool, bool]]:
    icons = []
    for raw in LIST.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        name, *flags = line.split()
        unknown = set(flags) - {"fill", "mirror"}
        if unknown:
            sys.exit(f"{LIST.name}: unknown flag(s) {sorted(unknown)} in line: {raw}")
        icons.append((name, "fill" in flags, "mirror" in flags))
    return icons


def drawable_name(name: str, fill: bool) -> str:
    return f"ms_{name}{'_fill' if fill else ''}"


def to_vector(svg: str, mirror: bool) -> str:
    box = VIEWBOX.search(svg)
    if not box:
        raise ValueError("no viewBox")
    min_x, min_y, width, height = (float(v) for v in box.groups())
    paths = PATH.findall(svg)
    if not paths:
        raise ValueError("no <path>")
    fmt = lambda v: str(int(v)) if v == int(v) else str(v)  # noqa: E731
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Material Symbols Rounded (Apache 2.0). Generated by scripts/fetch-material-symbols.py; do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        f'    android:viewportWidth="{fmt(width)}"',
        f'    android:viewportHeight="{fmt(height)}"',
    ]
    if mirror:
        lines.append('    android:autoMirrored="true"')
    lines[-1] += ">"
    translate = []
    if min_x:
        translate.append(f'android:translateX="{fmt(-min_x)}"')
    if min_y:
        translate.append(f'android:translateY="{fmt(-min_y)}"')
    indent = "    "
    if translate:
        lines.append(f"    <group {' '.join(translate)}>")
        indent = "        "
    for d in paths:
        lines.append(f'{indent}<path')
        lines.append(f'{indent}    android:fillColor="@android:color/black"')
        lines.append(f'{indent}    android:pathData="{d}" />')
    if translate:
        lines.append("    </group>")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def fetch(name: str, fill: bool) -> str:
    url = URL.format(name=name, style="fill1" if fill else "default")
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read().decode()


def main() -> None:
    force = "--force" in sys.argv
    prune = "--prune" in sys.argv
    icons = parse_list()
    OUT.mkdir(parents=True, exist_ok=True)
    wanted = set()
    failures = []
    fetched = 0
    for name, fill, mirror in icons:
        file = OUT / f"{drawable_name(name, fill)}.xml"
        wanted.add(file.name)
        if file.exists() and not force:
            continue
        try:
            file.write_text(to_vector(fetch(name, fill), mirror))
            fetched += 1
        except (urllib.error.URLError, ValueError) as error:
            failures.append(f"{name}{' (fill)' if fill else ''}: {error}")
    pruned = 0
    if prune:
        for file in OUT.glob("ms_*.xml"):
            if file.name not in wanted:
                file.unlink()
                pruned += 1
    print(f"{len(icons)} icons listed, {fetched} fetched, {pruned} pruned.")
    if failures:
        sys.exit("Failed:\n  " + "\n  ".join(failures))


if __name__ == "__main__":
    main()
